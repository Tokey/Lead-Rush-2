"""Build the GitHub copy of the LR2 Bot Lab and capture its eight scenarios as GIFs.

The artifact source is Docs/Bot/src/bot-lab.html (a page fragment; claude.ai wraps it in a document skeleton).
This script:
  1. wraps it into a standalone Docs/Bot/bot-lab.html (doctype, head, body), so it opens from disk or GitHub Pages;
  2. opens that page in headless Microsoft Edge with #gifgrid-<scenario>-<seconds per frame>-<frames>-dark, which makes
     the page itself simulate the scenario and draw every frame into one grid (the same code as the artifact);
  3. slices the grid screenshot into frames and writes Docs/Media/bot/lab-<n>-<slug>.gif.

Usage: python Tools/make_bot_lab_gifs.py   (Windows, Edge installed; Pillow required)
"""
from pathlib import Path
import re
import subprocess
import tempfile
import urllib.parse

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "Docs" / "Bot" / "src" / "bot-lab.html"
OUT_HTML = ROOT / "Docs" / "Bot" / "bot-lab.html"
OUT_GIF = ROOT / "Docs" / "Media" / "bot"
EDGE = Path(r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe")

SCENARIOS = ["spot-and-duel", "counter-strafe", "break-line-of-sight", "flank-a-camper",
             "retreat-and-heal", "armour-break-and-resupply", "investigate-a-shot", "contest-the-flag"]
STEP = 0.35      # simulated seconds per frame
FRAMES = 64      # 8 x 8 grid
CELL = (640, 400)
FRAME_MS = 150   # display time per frame (about 2.3x real time)


def build_standalone() -> None:
    frag = SRC.read_text(encoding="utf-8")
    cut = frag.index("</style>") + len("</style>")
    head, body = frag[:cut], frag[cut:]
    page = (
        "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, viewport-fit=cover\">\n"
        "<!-- Generated by Tools/make_bot_lab_gifs.py from Docs/Bot/src/bot-lab.html (the claude.ai artifact source). -->\n"
        "<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}"
        "body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>\n"
        + head + "\n</head>\n<body>\n" + body + "\n</body>\n</html>\n"
    )
    OUT_HTML.write_text(page, encoding="utf-8")
    print("wrote", OUT_HTML.relative_to(ROOT))


def capture(n: int, tmp: Path) -> Path:
    url = "file:///" + urllib.parse.quote(str(OUT_HTML).replace("\\", "/"), safe="/:") + f"#gifgrid-{n}-{STEP}-{FRAMES}-dark"
    shot = tmp / f"grid_{n}.png"
    cols = 8
    rows = (FRAMES + cols - 1) // cols
    cmd = [str(EDGE), "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
           f"--window-size={cols * CELL[0]},{rows * CELL[1]}", "--virtual-time-budget=9000",
           f"--screenshot={shot}", url]
    subprocess.run(cmd, check=True, timeout=180, capture_output=True)
    return shot


def slice_to_gif(grid_png: Path, n: int) -> Path:
    grid = Image.open(grid_png).convert("RGB")
    frames = []
    for f in range(FRAMES):
        x, y = (f % 8) * CELL[0], (f // 8) * CELL[1]
        frames.append(grid.crop((x, y, x + CELL[0], y + CELL[1])))
    # one shared palette keeps colours stable from frame to frame
    pal = frames[len(frames) // 2].quantize(colors=128, method=Image.Quantize.MEDIANCUT)
    q = [fr.quantize(palette=pal, dither=Image.Dither.NONE) for fr in frames]
    out = OUT_GIF / f"lab-{n + 1}-{SCENARIOS[n]}.gif"
    durations = [FRAME_MS] * (len(q) - 1) + [1800]
    q[0].save(out, save_all=True, append_images=q[1:], duration=durations, loop=0, optimize=True, disposal=1)
    return out


def main() -> None:
    build_standalone()
    OUT_GIF.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        for n in range(len(SCENARIOS)):
            grid = capture(n, tmp)
            out = slice_to_gif(grid, n)
            print(f"scenario {n + 1}: {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
